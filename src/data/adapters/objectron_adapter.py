import requests
from typing import Iterator, List
from src.data.schema import ItemInstanceRecord
from src.data.adapters.base import BaseDatasetAdapter

class ObjectronAdapter(BaseDatasetAdapter):
    """
    Adapter for the Objectron dataset.
    Reads the pre-processed manifest generated by ingest_objectron_tfrecords.py
    which already grouped frames by sequence_id and saved the images locally.
    """
    
    def __init__(self, target_categories: List[str], max_sequences_per_class: int = 50):
        self.target_categories = target_categories
        self.manifest_path = "data/interim/objectron_manifest.jsonl"

    def generate_manifest(self) -> Iterator[ItemInstanceRecord]:
        import json
        import os
        
        if not os.path.exists(self.manifest_path):
            print(f"Warning: {self.manifest_path} not found. Please run ingest_objectron_tfrecords.py first.")
            return
            
        with open(self.manifest_path, 'r') as f:
            for line in f:
                if not line.strip():
                    continue
                record_dict = json.loads(line)
                if record_dict['item_category'] in self.target_categories:
                    yield ItemInstanceRecord(**record_dict)
